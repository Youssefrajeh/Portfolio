def clamp(l):
    return max(1, min(15, l))


def add(level, q, correct, wrong):
    wrong = [w for w in dict.fromkeys(wrong) if w != correct][:3]
    if len(wrong) < 3 or q in seen_q:
        return
    seen_q.add(q)
    levels[clamp(level) - 1].append({"q": q, "options": [correct] + wrong, "answer": 0})


def pick(pool, correct, n=3, exclude=()):
    cands = [p for p in dict.fromkeys(pool) if p != correct and p not in exclude]
    random.shuffle(cands)
    return cands[:n]


